// Builds src/server/pdf/assets.generated.ts: the passport template and the skill stamps as
// base64, so the PDF generator works identically in dev, tests, CLI scripts and serverless
// bundles (which have no public/ folder).
//
// The static artwork (the cover's sticker cluster and the stamp legend on the "About" page)
// is drawn onto the template here, once, instead of on every generated passport.
// Run after replacing any file in src/server/pdf/assets/:  npm run assets:pdf
import { readFileSync, writeFileSync } from "node:fs";
import { degrees, PDFDocument } from "pdf-lib";

const dir = "src/server/pdf/assets";
const read = (file) => readFileSync(`${dir}/${file}`);

// [file, centre x, centre y, width, height, angle] in PDF points, drawn back to front.
const COVER_STICKERS = [
  ["cover-issued-by-btu.png", 631.4, 258.7, 209.6, 59.9, -6.96],
  ["cover-internationally-recognised.png", 493.8, 217.3, 132, 132, 0],
  ["cover-digital-passport.png", 623.4, 194.2, 176.8, 90.4, 0],
  ["cover-blockchain-verified.png", 739.4, 220.9, 148.4, 60, 15.3],
  ["cover-latest-skillset.png", 551.8, 116.6, 211.7, 45.3, -27.57],
];
// One example of each stamp beside its explanation.
const ABOUT_STAMPS = [
  ["AI_SKILL.png", 503, 455, 50, 43.3, 0],
  ["AI_APPLIED.png", 718.5, 453, 89, 28.6, 0],
  ["AI_ADVANCED.png", 565, 302, 44, 44, 0],
];

const pdf = await PDFDocument.load(read("passport-template.pdf"), { updateMetadata: false });
const [cover, about] = pdf.getPages();
for (const [page, items] of [
  [cover, COVER_STICKERS],
  [about, ABOUT_STAMPS],
]) {
  for (const [file, cx, cy, width, height, deg] of items) {
    const t = (deg * Math.PI) / 180;
    page.drawImage(await pdf.embedPng(read(file)), {
      x: cx - (width / 2) * Math.cos(t) + (height / 2) * Math.sin(t),
      y: cy - (width / 2) * Math.sin(t) - (height / 2) * Math.cos(t),
      width,
      height,
      rotate: degrees(deg),
    });
  }
}
const template = await pdf.save({ useObjectStreams: false });

const exports = {
  template: Buffer.from(template),
  AI_SKILL: read("AI_SKILL.png"),
  AI_APPLIED: read("AI_APPLIED.png"),
  AI_ADVANCED: read("AI_ADVANCED.png"),
};
let out = "// Generated by scripts/embed-pdf-assets.mjs — do not edit.\n";
for (const [name, bytes] of Object.entries(exports)) {
  out += `export const ${name} = "${bytes.toString("base64")}";\n`;
}
writeFileSync("src/server/pdf/assets.generated.ts", out);
console.log("Wrote src/server/pdf/assets.generated.ts");
