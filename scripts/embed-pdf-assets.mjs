// Embeds the passport template and stamp images as base64 so the PDF generator works
// identically in dev, tests, CLI scripts and serverless bundles (which have no public/ folder).
// Run after replacing any file in src/server/pdf/assets/:  node scripts/embed-pdf-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/server/pdf/assets";
const files = {
  template: "passport-template.pdf",
  AI_SKILL: "AI_SKILL.png",
  AI_APPLIED: "AI_APPLIED.png",
  AI_ADVANCED: "AI_ADVANCED.png",
};
let out = "// Generated by scripts/embed-pdf-assets.mjs — do not edit.\n";
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = "${readFileSync(`${dir}/${file}`).toString("base64")}";\n`;
}
writeFileSync("src/server/pdf/assets.generated.ts", out);
console.log("Wrote src/server/pdf/assets.generated.ts");
